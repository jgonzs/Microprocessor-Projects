#define SPEAKER_PIN 1

//Timer clock = 4 MHz MSI/(PSC+1) = 1 MHz
#define TIMER_CLK_HZ 1000000

void delayf(uint32_t ms) {
    TIM2->ARR = (TIMER_CLK_HZ/1000) - 1;
    TIM2->EGR |= (1 << 0);
    TIM2->SR  &= ~(1 << 0);
    for (uint32_t i = 0; i < ms; i++) {
        while (!(TIM2->SR & 1)){}
        TIM2->SR &= ~(1 << 0);
    }
}

void freqf(int freq, uint32_t cycles) {
    TIM2->ARR = (TIMER_CLK_HZ /(2*freq)) - 1;
    TIM2->EGR |= (1 << 0);
    TIM2->SR  &= ~(1 << 0);
    for (uint32_t i = 0; i < cycles; i++) {
        while (!(TIM2->SR & 1)){}
        TIM2->SR &= ~(1 << 0);
        GPIOA->ODR ^= (1 << SPEAKER_PIN); //Toggle bit with XOR
    }
}

int main(void) {
    int i = 0;

    //Turn on Clock
    RCC->AHB2ENR  |= (1 << 0); //GPIOAEN = 1
    RCC->APB1ENR1 |= (1 << 0); //TIM2EN = 1

    GPIOA->MODER &= ~(3 << (SPEAKER_PIN * 2));
    GPIOA->MODER |=  (1 << (SPEAKER_PIN * 2));

    
    TIM2->PSC = 3; //Set Prescaler
    TIM2->EGR |= (1 << 0); //Reset Counter to 0
    TIM2->SR  &= ~(1 << 0); //Clear Update Flag
    TIM2->CR1 |= 1; //Enable Counter

    while (!(notes[i][0] == 0 && notes[i][1] == 0)) {
        int freq  = notes[i][0]; //Grab frequency from array
        int delay = notes[i][1]; //Grab delay from array
        if (freq == 0) {        //If no note is played, just hold
            delayf(delay); //Calls delay function
        } else {
            uint32_t cycles = 2*freq*delay/1000; //When to toggle
            freqf(freq, cycles); //Calls frequency function
        }
        
        i++; //Go to next line in array

        GPIOA->ODR &= ~(1 << SPEAKER_PIN); //clear ODR
    }
}